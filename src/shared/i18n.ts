const DICTS: Record<Lang, Record<MessageKey, string>> = { ru, en };

let current: Lang = "ru";

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function isLang(v: unknown): v is Lang {
  return LANGS.includes(v as Lang);
}

/** Russian for ru/uk/be/kk locales, English otherwise. */
export function langForLocale(locale: string): Lang {
  return /^(ru|uk|be|kk)\b/i.test(locale) ? "ru" : "en";
}

export function locale(): string {
  return current === "ru" ? "ru-RU" : "en-US";
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  return tIn(current, key, vars);
}

/** `t` in a specific language regardless of the current one. */
export function tIn(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = DICTS[lang][key] ?? ru[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text;
}

export const LANG_NAMES: Record<Lang, string> = { ru: "Русский", en: "English" };
